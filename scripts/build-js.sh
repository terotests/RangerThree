#!/usr/bin/env bash
# The three crate as JavaScript: Ranger compiles three/src/lib.rs (the same
# strict Rust cargo builds) to es6, wrapped as one script that defines
# `RangerThreeCore` (the Rust types by name). js/three.js puts three.js's
# API (`THREE`) over it.
#
#   scripts/build-js.sh            -> build/rangerthree-core.js
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
# shellcheck source=deps.sh
source "$ROOT/scripts/deps.sh"
ensure_ranger
OUT="$ROOT/build"
mkdir -p "$OUT"
LOG="$OUT/rangerthree-core.log"
(cd "$ROOT/three" && node "$RANGER/dist/rgrc.js" -l=es6 src/lib.rs -d="$OUT" -o=rangerthree-core.raw.js -no-color) >"$LOG" 2>&1 || true
if grep -q '\[FAIL' "$LOG" || [[ ! -s "$OUT/rangerthree-core.raw.js" ]]; then
  grep -E '\[FAIL' -A3 "$LOG" | head -40
  echo "build-js: Ranger did not compile three/src/lib.rs (log: $LOG)" >&2
  exit 1
fi
node - "$OUT/rangerthree-core.raw.js" "$OUT/rangerthree-core.js" <<'JS'
const fs = require("fs");
const [src, dst] = process.argv.slice(2);
const code = fs.readFileSync(src, "utf8");
const names = [...code.matchAll(/^class (\w+)/gm)].map((m) => m[1]);
fs.writeFileSync(dst, "// Generated by scripts/build-js.sh from three/src (Ranger es6). Do not edit.\n" +
  "var RangerThreeCore = (function () {\n" + code + "\nreturn { " + names.join(", ") + " };\n})();\n");
JS
rm -f "$OUT/rangerthree-core.raw.js"
echo "build/rangerthree-core.js ($(wc -c <"$OUT/rangerthree-core.js") bytes)"
