// Writes three/src/renderers/ltc_table.rs: the linearly transformed cosine
// tables for rect area lights (Heitz et al. 2016), 64 x 64 RGBA each, as
// three.js ships them in examples/jsm/lights/RectAreaLightTexturesLib.js.
// Values keep six significant digits and are written without exponents
// (values under 1e-9 become 0), which the Ranger writers print as given.
//   node scripts/gen-ltc-table.js [path to RectAreaLightTexturesLib.js]
const fs = require("fs");
const path = require("path");
const src = fs.readFileSync(process.argv[2] || path.join(__dirname, "../tmp/three-ref/three/examples/jsm/lights/RectAreaLightTexturesLib.js"), "utf8");
function grab(name) {
  const i = src.indexOf("const " + name + " = [");
  const j = src.indexOf("];", i);
  return new Function("return " + src.slice(src.indexOf("[", i), j + 1))();
}
function num(x) {
  if (Math.abs(x) < 1e-9) return "0.0";
  let s = Number(x.toPrecision(6)).toFixed(12).replace(/0+$/, "");
  if (s.endsWith(".")) s += "0";
  return s;
}
function body(a) {
  const rows = [];
  for (let i = 0; i < a.length; i += 16) rows.push("        " + a.slice(i, i + 16).map(num).join(", ") + ",");
  return rows.join("\n");
}
const m1 = grab("LTC_MAT_1"), m2 = grab("LTC_MAT_2");
if (m1.length !== 16384 || m2.length !== 16384) throw new Error("unexpected table sizes " + m1.length + " " + m2.length);
const out = `//! Generated by scripts/gen-ltc-table.js: the linearly transformed cosine
//! tables rect area lights use (Heitz, Dupuy, Hill and Neubelt 2016), 64 x 64
//! RGBA texels each, rows by sqrt(1 - n.v), columns by roughness.

use ranger::prelude::*;

/// The inverse transform matrix entries (m00, m02, m20, m22 of the fit).
pub fn ltc_1() -> Vec<f64> {
    vec![
${body(m1)}
    ]
}

/// The Fresnel terms (x, y) and the form factor scale.
pub fn ltc_2() -> Vec<f64> {
    vec![
${body(m2)}
    ]
}
`;
fs.writeFileSync(path.join(__dirname, "../three/src/renderers/ltc_table.rs"), out);
console.log("ltc_table.rs", out.length, "bytes");
