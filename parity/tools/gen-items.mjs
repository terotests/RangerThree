// and scenes.mjs. Run after changing either.
//
//   node web/three/parity/tools/gen-items.mjs
import fs from "node:fs";
import path from "node:path";
import { valueProbes, PARITY } from "./probes.mjs";
import { SCENE_ITEMS } from "../scenes.mjs";
const items = [];
for (const p of valueProbes()) {
  const name = p.id.slice(6);
  items.push({ id: p.id, axis: "value", group: name.split(".")[0], title: `THREE.${name}`, test: "value" });
}
for (const it of SCENE_ITEMS) {
  const test = it.scene ? "picture" : it.kit ? "kit" : it.example ? "example" : "perf";
  items.push({ id: it.id, axis: it.axis, group: it.id.split(":")[1].split(".")[0], title: it.title, test });
}
const by = {};
for (const i of items) by[i.axis] = (by[i.axis] || 0) + 1;
fs.writeFileSync(path.join(PARITY, "items.json"), JSON.stringify({
  about: "Three parity items (web/three/parity/PARITY.md). axis value: a THREE.* call's value equals three.js r185's; render/r3f with test picture: the scene drawn by rangerthree on the GPU looks like three.js's picture of it (R3F rules); kit: React Three Fiber behaviour checked in the .tsx kit; example: a three.js example runs as a .tsx document; perf: the GPU path against three.js. Generated by tools/gen-items.mjs; status is in results/three-parity.json.",
  counts: by, total: items.length, items,
}, null, 1) + "\n");
console.log(`items.json: ${items.length} items`, by);
